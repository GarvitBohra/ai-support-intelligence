from pathlib import Path

import joblib
import streamlit as st


PROJECT_ROOT = Path(__file__).resolve().parent
MODEL_PATH = PROJECT_ROOT / "models" / "ticket_classifier.joblib"


@st.cache_resource
def load_model():
    return joblib.load(MODEL_PATH)


st.set_page_config(
    page_title="AI Support Intelligence",
    page_icon="🎫",
    layout="centered",
)

st.markdown(
    """
    <style>
    .stApp { background: #f5f7fb; }
    .block-container { max-width: 850px; padding-top: 3rem; padding-bottom: 4rem; }
    .hero { padding: 1.8rem 2rem; border-radius: 18px; color: white;
            background: linear-gradient(120deg, #172554, #2563eb); margin-bottom: 1.5rem; }
    .hero h1 { margin: 0 0 .4rem; font-size: 2.1rem; }
    .hero p { margin: 0; color: #dbeafe; font-size: 1.03rem; }
    [data-testid="stForm"] { background: white; padding: 1.5rem;
        border: 1px solid #e2e8f0; border-radius: 16px; }
    [data-testid="stMetric"] { background: white; padding: 1rem 1.2rem;
        border: 1px solid #e2e8f0; border-radius: 14px; }
    </style>
    """,
    unsafe_allow_html=True,
)

st.markdown(
    """
    <div class="hero">
      <h1>Support ticket classifier</h1>
      <p>Turn a customer message into a clear ticket category in seconds.</p>
    </div>
    """,
    unsafe_allow_html=True,
)

with st.form("ticket_form"):
    subject = st.text_input(
        "Ticket subject",
        placeholder="For example: I was charged twice",
        max_chars=300,
    )
    description = st.text_area(
        "Customer message",
        placeholder="Describe the issue in the customer's own words…",
        height=180,
        max_chars=10000,
    )
    submitted = st.form_submit_button("Classify ticket", type="primary", use_container_width=True)

if submitted:
    if not subject.strip() or not description.strip():
        st.warning("Enter both a subject and a customer message to classify the ticket.")
    else:
        try:
            model = load_model()
            message = f"{subject.strip()} {description.strip()}"
            prediction = str(model.predict([message])[0])
            probabilities = model.predict_proba([message])[0]
            classes = model.classes_
            ranked = sorted(zip(classes, probabilities), key=lambda item: item[1], reverse=True)
            confidence = float(ranked[0][1])

            st.success("Classification complete")
            result, confidence_column = st.columns([2, 1])
            result.metric("Predicted category", prediction)
            confidence_column.metric("Model confidence", f"{confidence:.0%}")

            with st.expander("See other possible categories"):
                for category, probability in ranked:
                    st.write(f"**{category}** — {probability:.1%}")
                    st.progress(float(probability))
        except Exception:
            st.error("The classifier could not load or process this ticket.")

st.caption("Predictions are generated by the project's trained ticket classification model.")
